struct ImagePreviewTests {
    private func image(width: Int = 4, height: Int = 2) throws -> CGImage {
        let context = try #require(
            CGContext(
                data: nil, width: width, height: height, bitsPerComponent: 8,
                bytesPerRow: width * 4, space: CGColorSpaceCreateDeviceRGB(),
                bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue))
        context.setFillColor(CGColor(red: 1, green: 0, blue: 0, alpha: 0.5))
        context.fill(CGRect(x: 0, y: 0, width: width, height: height))
        return try #require(context.makeImage())
    }
    private func encoded(_ image: CGImage, type: String, frames: Int = 1, orientation: Int = 1) throws -> Data {
        let data = NSMutableData()
        let writer = try #require(CGImageDestinationCreateWithData(data, type as CFString, frames, nil))
        for _ in 0..<frames {
            CGImageDestinationAddImage(writer, image, [kCGImagePropertyOrientation: orientation] as CFDictionary)
        }
        #expect(CGImageDestinationFinalize(writer))
        return data as Data
    }
    @Test func generatedRasterFormatsDecodeWithoutTextOrAppKit() throws {
        let source = try image()
        let formats = [
            ("public.png", "png"), ("public.jpeg", "jpg"), ("com.compuserve.gif", "gif"),
            ("public.tiff", "tiff"), ("com.microsoft.bmp", "bmp"), ("public.jpeg-2000", "jp2"),
            ("com.microsoft.ico", "ico"), ("com.apple.icns", "icns"), ("public.heic", "heic"), ("public.avif", "avif"),
        ]
        let writers = CGImageDestinationCopyTypeIdentifiers() as! [String]
        var verified: [String] = []
        for (type, suffix) in formats {
            if !writers.contains(type) { continue }
            // ICO requires square canonical icon dimensions.
            let input =
                (type == "com.microsoft.ico" || type == "com.apple.icns") ? try image(width: 16, height: 16) : source
            let data = try encoded(input, type: type)
            let value = try ImagePreviewDecoder.decode(data, path: "fixture." + suffix)
            #expect(value.image.width == input.width && value.image.height == input.height)
            #expect(value.pixelSize == CGSize(width: input.width, height: input.height))
            #expect(value.byteCount == data.count && value.frameCount == 1)
            verified.append(suffix)
        }
        #expect(Set(["png", "jpg", "gif", "tiff", "bmp"]).isSubset(of: Set(verified)))
        print("IMAGE_FORMAT_PASS: " + verified.joined(separator: ","))
    }
    @Test func webpLosslessSampleDecodesWithAlpha() throws {
        // Owned 3x2 constant-color fixture, generated by Pillow's WebP writer.
        let bytes = try #require(Data(base64Encoded: "UklGRhwAAABXRUJQVlA4TA8AAAAvAkAAEAcQ/Y8CBiKi/wEA"))
        let value = try ImagePreviewDecoder.decode(bytes, path: "transparent.webp")
        #expect(value.pixelSize == CGSize(width: 3, height: 2))
        #expect(value.format == "WEBP")
        let rgba = try #require(value.image.dataProvider?.data) as Data
        #expect((126...129).contains(Int(rgba[3])))
    }
    @Test func gifUsesFirstFrameAndReportsMultipleFrames() throws {
        let value = try ImagePreviewDecoder.decode(
            encoded(image(), type: "com.compuserve.gif", frames: 2), path: "two.gif")
        #expect(value.frameCount == 2 && value.image.width == 4)
    }
    @Test func orientationAndTransparentPixelsAreAppliedInTheProjection() throws {
        let source = try image()
        let rotated = try ImagePreviewDecoder.decode(
            encoded(source, type: "public.tiff", orientation: 6), path: "rotated.tiff")
        #expect(rotated.pixelSize == CGSize(width: 2, height: 4))
        #expect(rotated.image.width == 2 && rotated.image.height == 4)
        let transparent = try ImagePreviewDecoder.decode(encoded(source, type: "public.png"), path: "misnamed.JPG")
        #expect(transparent.format == "PNG")
        let bytes = try #require(transparent.image.dataProvider?.data) as Data
        #expect((126...129).contains(Int(bytes[3])))
    }
    @Test func largeImagesUseABoundedDecodeRatherThanFullResolution() throws {
        let source = try image(width: 5000, height: 2)
        let value = try ImagePreviewDecoder.decode(encoded(source, type: "public.png"), path: "wide.png")
        #expect(value.pixelSize.width == 5000 && value.downsampled)
        #expect(value.image.width <= ImagePreviewDecoder.maximumDecodedEdge)
    }
    @Test func svgBridgeReturnsOwnedPixelsAndRejectsExternalContent() throws {
        let good = Data(
            "<svg xmlns='http://www.w3.org/2000/svg' width='40' height='20'><rect width='40' height='20' fill='blue'/></svg>"
                .utf8)
        let value = try ImagePreviewDecoder.decode(good, path: "icon.SVG")
        #expect(value.format == "SVG" && value.pixelSize == CGSize(width: 40, height: 20))
        #expect(value.image.width == 2048 && value.image.height == 1024)
        for text in [
            "broken", "<svg xmlns='http://www.w3.org/2000/svg'><image href='https://example.invalid/x.png'/></svg>",
        ] {
            #expect(throws: (any Error).self) { try ImagePreviewDecoder.decode(Data(text.utf8), path: "bad.svg") }
        }
    }
    @Test func dispatchUsesKnownImageExtensionsAndMalformedDataFailsLocally() {
        for path in ["icon.PNG", "photo.JPEG", "sprite.webp", "a.heic", "b.avif", "icon.icns", "file.svg", "scan.nef"] {
            #expect(ImagePreviewFormat.matches(path))
        }
        for path in ["main.swift", "pubspec.yaml", "a.png.dart", "package.json", "README"] {
            #expect(!ImagePreviewFormat.matches(path))
        }
        for bytes in [Data(), Data("not a picture".utf8), Data([0x89, 0x50, 0x4e, 0x47])] {
            #expect(throws: (any Error).self) { try ImagePreviewDecoder.decode(bytes, path: "broken.png") }
        }
    }
    @Test func fileReadsStayInsideRootAndRejectLinksAndSpecialFiles() throws {
        let root = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: root) }
        let file = root.appendingPathComponent("图片 %.png")
        try Data([1, 2, 3]).write(to: file)
        #expect(try PreviewFileIO.read(root: root, path: "图片 %.png") == Data([1, 2, 3]))
        try FileManager.default.createSymbolicLink(
            atPath: root.appendingPathComponent("link.png").path, withDestinationPath: file.path)
        try FileManager.default.createSymbolicLink(
            atPath: root.appendingPathComponent("folder").path, withDestinationPath: root.path)
        #expect(mkfifo(root.appendingPathComponent("pipe.png").path, 0o600) == 0)
        for path in ["../escape.png", "/tmp/file.png", "link.png", "folder/图片 %.png", "pipe.png", "a//b", "a\0.png"] {
            #expect(throws: (any Error).self) { try PreviewFileIO.read(root: root, path: path) }
        }
        let fd = open(root.appendingPathComponent("large.png").path, O_CREAT | O_WRONLY, 0o600)
        #expect(fd >= 0)
        if fd >= 0 {
            #expect(ftruncate(fd, off_t(PreviewFileIO.maximumBytes + 1)) == 0)
            close(fd)
        }
        #expect(throws: (any Error).self) { try PreviewFileIO.read(root: root, path: "large.png") }
    }
    @Test func canceledReadsDoNotStartOpeningTheFile() async {
        let operation = Task.detached(priority: .utility) {
            withUnsafeCurrentTask { $0?.cancel() }
            return try PreviewFileIO.read(root: URL(fileURLWithPath: "/nonexistent"), path: "x.png")
        }
        do {
            _ = try await operation.value
            Issue.record("取消未阻止读取")
        } catch { #expect(error is CancellationError) }
    }
}
struct ImagePreviewGeometryTests {
    @Test func fitNeverEnlargesSmallImagesAndKeepsLargeImagesWithinMargins() {
        let state = ImagePreviewZoom()
        let viewport = CGSize(width: 800, height: 600)
        for pixels in [CGSize(width: 40, height: 20), CGSize(width: 10000, height: 4000)] {
            let factor = state.factor(pixels: pixels, viewport: viewport)
            let layout = ImagePreviewLayout(pixels: pixels, viewport: viewport, scale: factor)
            #expect(factor <= 1)
            #expect(layout.image.width <= viewport.width - 32 && layout.image.height <= viewport.height - 32)
            #expect(layout.extent == viewport)
        }
    }
    @Test func zoomPreservesTheImagePointBeneathThePointer() {
        let pixels = CGSize(width: 2000, height: 1000)
        let viewport = CGSize(width: 400, height: 300)
        let old = ImagePreviewLayout(pixels: pixels, viewport: viewport, scale: 1)
        let next = ImagePreviewLayout(pixels: pixels, viewport: viewport, scale: 2)
        let origin = CGPoint(x: 300, y: 200)
        let anchor = CGPoint(x: 100, y: 120)
        let moved = next.preservingAnchor(from: old, origin: origin, anchor: anchor, viewport: viewport)
        let oldX = (origin.x + anchor.x - old.image.minX) / old.image.width
        let newX = (moved.x + anchor.x - next.image.minX) / next.image.width
        let oldY = (origin.y + anchor.y - old.image.minY) / old.image.height
        let newY = (moved.y + anchor.y - next.image.minY) / next.image.height
        #expect(abs(oldX - newX) < 0.00001 && abs(oldY - newY) < 0.00001)
    }
    @Test func resizeAtFarEdgesClampsOnlyAfterPreservingTheOldCenter() {
        let pixels = CGSize(width: 2000, height: 2000)
        let oldSize = CGSize(width: 400, height: 400)
        let newSize = CGSize(width: 800, height: 800)
        let old = ImagePreviewLayout(pixels: pixels, viewport: oldSize, scale: 1)
        let next = ImagePreviewLayout(pixels: pixels, viewport: newSize, scale: 1)
        let offset = next.preservingAnchor(
            from: old, origin: CGPoint(x: 1500, y: 1500), anchor: CGPoint(x: 200, y: 200),
            viewport: newSize, newAnchor: CGPoint(x: 400, y: 400))
        #expect(offset == CGPoint(x: 1232, y: 1232))
    }
    @Test func manualZoomAndPanClampAtSupportedLimits() {
        var state = ImagePreviewZoom()
        let pixels = CGSize(width: 100, height: 80)
        let viewport = CGSize(width: 200, height: 150)
        state.set(.infinity)
        #expect(!state.fits && state.factor(pixels: pixels, viewport: viewport) == 1)
        state.set(100)
        #expect(state.factor(pixels: pixels, viewport: viewport) == 16)
        let layout = ImagePreviewLayout(pixels: pixels, viewport: viewport, scale: 16)
        #expect(layout.clamp(origin: CGPoint(x: -100, y: -100), viewport: viewport) == .zero)
        #expect(
            layout.clamp(origin: CGPoint(x: 10000, y: 10000), viewport: viewport)
                == CGPoint(x: layout.extent.width - viewport.width, y: layout.extent.height - viewport.height))
        state.fit()
        #expect(state.fits)
    }
}
